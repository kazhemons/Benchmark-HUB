package com.majestic.benchjitter.ui

/**
 * Паспорт теста для подвала экрана: название, техническое описание методики и
 * описание каждого измерителя — по одному на строку. Текст намеренно честный:
 * где метрика косвенная (чтение через кэш, GPU-стадия не на всех устройствах)
 * — это написано прямо в описании.
 */
internal class ModeDoc(
    val title: String,
    val tech: String,
    val values: List<Pair<String, String>>,
)

private val statsCommon = listOf(
    "Среднее (mean)" to "среднее значение измерений в последние 400 сэмплов",
    "Стандартное отклонение (σ)" to "разброс значений вокруг среднего — величина нестабильности; чем меньше, тем стабильнее система",
    "Минимум / Максимум" to "наилучшее и наихудшее измерение за весь прогон (накопительные)",
    "Медиана (p50)" to "половина измерений лучше этого значения, половина хуже; устойчивая «типичная» величина, нечувствительная к выбросам",
    "Перцентили p90 / p95 / p99" to "пороги, ниже которых оказывается 90/95/99% измерений; хвосты распределения показывают наихудшие 10/5/1% случаев",
)

// Общие для стресс-режимов: наблюдение за нагревом устройства во время теста.
private val thermalCommon = listOf(
    "Температура — аккумулятор" to "показание системной информации о батарее, доступно на любом устройстве; ближайшая доступная оценка общего нагрева корпуса; отдельно ведётся максимум за прогон",
    "Температура — CPU / GPU / RAM" to "берётся из температурных сенсоров либо системных тепловых зон (/sys/class/thermal) — если производитель устройства их опубликовал; при нескольких источниках одной категории (кластеры) показывается самый горячий",
    "Тепловой статус устройства" to "системная оценка перегрева по шкале Android (Android 10+): норма → лёгкий → умеренный → сильный → критический → аварийный → готовность к thermal shutdown; с умеренного уровня начинается активный троттлинг",
)

internal fun modeDoc(mode: BenchMode): ModeDoc = when (mode) {
    BenchMode.FRAMES -> ModeDoc(
        title = "Тест: ${mode.label}",
        tech = "Приложение непрерывно рендерит анимацию и берёт метку старта каждого кадра через withFrameNanos " +
            "(источник метки — сигнал vsync, тот же, что у Choreographer). Интервал между соседними метками = " +
            "фактическое время кадра дисплея. Номинальный период вычисляется как медиана последних 120 интервалов " +
            "(= период экрана). Пропущенным считается кадр, интервал которого длиннее 1,5 номинального. Паузы " +
            "приложения (гэпы длиннее 100 мс: сворачивание, блокировка экрана) в статистику не попадают, но " +
            "считаются отдельно. Статистика считается по последним 400 интервалам, min/max — накопительные.",
        values = listOf(
            "Номинал (Гц и период)" to "медианный интервал кадра; показывает, на какой частоте реально работает экран (может отличаться от максимум, заявленного в настройках)",
            "Замерено FPS" to "фактическое число отрисованных кадров в секунду за время прогона",
            "Пропущено кадров" to "количество интервалов длиннее 1,5 номинала — провалы рисования",
            "Гэпы после паузы" to "разрывы рендеринга длиннее 100 мс (пауза приложения, блокировка) — это не дефект, но их видно на графике как отдельные точки",
            "График «отклонение от номинала»" to "штрих выше центральной линии — кадр запаздывал, ниже — спешил; красные — превышен порог пропуска",
            "Пульс" to "полоса, синхронизируемая с реальными кадрами: ровный бег = кадровый ритм не ломается",
        ) + statsCommon,
    )

    BenchMode.WAKE -> ModeDoc(
        title = "Тест: ${mode.label}",
        tech = "Отдельный поток выбранного приоритета планирования ждёт абсолютных дедлайнов: цикл LockSupport.parkNanos " +
            "до точной метки времени с репарком (ложные пробуждения не считаются). Дедлайны выстраиваются через равные " +
            "интервалы независимо от того, когда поток проснулся фактически. Измеряется опоздание = фактическое " +
            "пробуждение минус дедлайн. Просроченной считается метка, если опоздание больше половины интервала. " +
            "Статистика по последним 400 опозданиям, min/max — накопительные.",
        values = listOf(
            "Интервал пробуждения" to "как часто поток должен просыпаться (0,5–10 мс); смена интервала начинает новый прогон",
            "Приоритет потока" to "класс планирования ОС: «Фон», «Обычный», «Хороший», «Срочный» — чем выше, тем агрессивнее ОС отдаёт поток процессору",
            "Просрочено меток" to "сколько пробуждений опоздали больше чем на половину интервала — прямые провалы планировщика",
            "Идеал" to "всё распределение вплотную у нуля; типичная поправка ОС — единицы микросекунд–миллисекунды в зависимости от планировщика",
        ) + statsCommon,
    )

    BenchMode.CPU -> ModeDoc(
        title = "Тест: ${mode.label}",
        tech = "N потоков (1 / 2 / 4 / все ядра) выполняют цепочку взаимозависимых float-операций (квадратный корень, " +
            "каждое звено зависит от предыдущего — свернуть или выкинуть их оптимизатор не может). Квант = 100 000 " +
            "операций. Каждую секунду измеритель снимает, сколько квантов завершили все потоки, — получается профиль " +
            "скорости из окон по 1 секунде. По профилю считаются mean/σ/перцентили; скорость приводится к Моп/с " +
            "(миллионам операций в секунду суммарно).",
        values = listOf(
            "Потоки" to "число одновременно работающих рабочих потоков; смена числа перезапускает измерение",
            "Средний темп (Моп/с)" to "средняя суммарная скорость — главный сравнительный показатель между устройствами и режимами энергосбережения",
            "Выполнено операций" to "суммарное число выполненных float-операций всеми потоками за прогон",
            "Относительный разброс" to "σ как процент от среднего темпа: тепловой и энерго троттлинг; ровный прогресс <1–2%",
        ) + statsCommon + thermalCommon,
    )

    BenchMode.RAM -> ModeDoc(
        title = "Тест: ${mode.label}",
        tech = "Поток по кругу выделяет чанки по 16 МБ и заполняет их целиком (касание каждой страницы переводит " +
            "память из виртуальной в физическую). Все чанки удерживаются в списке — куча растёт, пока позволяет " +
            "лимит кучи процесса (Runtime maxMemory минус уже занятое минус запас 48 МБ) или пока не случается " +
            "OutOfMemoryError. Измеряется время заполнения каждого чанка — по этим временам считается распределение.",
        values = listOf(
            "Удерживается" to "суммарный объём заполненной и удерживаемой памяти — фактически достигнутый потолок",
            "Лимит кучи процесса" to "оценка верхней границы кучи, доступной приложению (не путать с общей памятью устройства)",
            "Скорость заполнения (МБ/с)" to "производительность подсистемы памяти: выделять + заполнить + привести к резидентности",
            "Время чанка" to "длительность заполнения одного чанка 16 МБ; по нему считаются mean/σ/p99",
            "Потолок достигнут" to "«да» — следующий чанк не влезает (предел найден); «нет» — память продолжает расти",
            "Сброс" to "освобождает всю удержанную память и обнуляет результаты",
        ) + statsCommon + thermalCommon,
    )

    BenchMode.COMBO -> ModeDoc(
        title = "Тест: ${mode.label}",
        tech = "Движки CPU и RAM работают одновременно: рабочие потоки наматывают операции, а параллельный поток " +
            "набивает кучу до потолка. Сравнивайте результаты с одиночными тестами «Стресс CPU» и «Стресс RAM»: " +
            "падение темпа и рост σ показывают, как насыщение памяти мешает процессору держать частоты (и наоборот).",
        values = listOf(
            "Часть CPU" to "метрики теста «Стресс CPU» в условиях одновременной нагрузки памятью",
            "Часть RAM" to "метрики теста «Стресс RAM» в условиях загруженных ядер",
        ) + statsCommon + thermalCommon,
    )

    BenchMode.GPU -> ModeDoc(
        title = "Тест: ${mode.label}",
        tech = "Canvas-сцена из ~220 кругов с радиальными градиентами перерисовывается каждый кадр — постоянная " +
            "нагрузка на GPU (движок HWUI). Интервалы кадров собираются по меткам vsync, как в тесте «Джиттер " +
            "кадров». Время GPU-стадии кадра — длительность GPU_DURATION из FrameMetrics (подписка " +
            "addOnFrameMetricsAvailableListener на Window активности). Если средняя GPU-стадия близка к периоду " +
            "кадра или превышает его — GPU не успевает, и начнутся пропуски. Если устройство подписку не приняло, " +
            "остаётся только кадровая метрика под нагрузкой.",
        values = listOf(
            "Замерено FPS тяжёлой сцены" to "фактическая скорость отрисовки под нагрузкой; сравнивается с FPS лёгкого режима «Джиттер кадров» — это и есть «просадка» от GPU-работы",
            "GPU-стадия (mean)" to "среднее время, которое GPU тратит на отрисовку одного кадра; сравнивайте с периодом кадра (16,7 мс при 60 Гц)",
            "GPU-стадия (p95/p99)" to "самые тяжёлые кадры — сложные композитные сцены или троттлинг GPU",
            "Пропущено кадров" to "провалы рисования под нагрузкой",
        ) + statsCommon + thermalCommon,
    )

    BenchMode.ROM -> ModeDoc(
        title = "Тест: ${mode.label}",
        tech = "Цикл с файлом 64 МБ в cacheDir приложения: последовательная запись кусками по 1 МБ; в конце файла — " +
            "fsync (сбрасывает данные на физический носитель — без него измерялась бы скорость кэша). Затем файл " +
            "читается обратно (суммирование прочитанных байтов не даёт «прочитать ноль») и удаляется; цикл " +
            "повторяется, пока идёт прогон. Каждое время куска — сэмпл; по нему считаются МБ/с и перцентили. " +
            "Чтение идёт через страничный кэш файловой системы, поэтому отражает потолок кэша, а не «сырую» " +
            "скорость флеша.",
        values = listOf(
            "Запись (МБ/с)" to "скорость записи кусков при fsync на файле — основная сравнительная метрика носителя; медиана и хвосты p95/p99 показывают разброс поведения контроллера флеша",
            "Чтение (МБ/с)" to "скорость чтения свежезаписанного файла из страничного кэша — показывает кэш, а не носитель",
            "Проходов завершено" to "число полных циклов запись → чтение → удаление",
            "Разброс времени куска (σ)" to "нестабильность записи: фоновые задачи, сборка мусора контроллера флеша, нагрев",
            "Свободное место" to "при нехватке места на разделе прогон останавливается и помечается предупреждением",
        ) + statsCommon + thermalCommon,
    )
    BenchMode.DEVICE -> ModeDoc(
        title = "Раздел: ${mode.label}",
        tech = "Справка об устройстве без нагрузочного теста: идентификация и SoC берутся из системных API " +
            "(на Android 12+ — производитель/модель чипа), максимумы ядер — из файлов cpufreq в /sys/devices/system/cpu, " +
            "объём памяти — из системной информации о памяти, состояние раздела данных — из измерителя файловой системы, " +
            "экран — из параметров дисплея. Температуры и диагностика нагрева — те же источники, что и в стресс-режимах.",
        values = listOf(
            "Ядер CPU и максимумы" to "количество ядер и их номинальные максимальные частоты (группами); буст и ограничения по энергобюджету во время работы не учитываются; ядра без таких файлов не показываются",
            "Оперативная память (видимая приложению)" to "полный объём по данным системы — ориентировочная величина: часть памяти занята системой и приложениям недоступна",
            "Хранилище (раздел данных)" to "свободно/всего на разделе, где живут данные приложения; это ёмкость раздела, а не скорость носителя",
            "Экран" to "разрешение в пикселях, плотность dpi, нативная частота обновления дисплея (если доступна системе)",
        ) + thermalCommon,
    )
}
